import { App, TFile, normalizePath } from "obsidian";
import { WorkoutStore } from "./store";
import { Exercise, SetEntry, WorkoutSession } from "./types";
import {
	doneSets,
	e1rm,
	sessionDurationMin,
	sessionRecords,
	sessionSetCount,
	sessionVolume,
} from "./stats";
import { formatDate, formatDuration, formatNumber, formatTimeOfDay, sanitizeFileName } from "./utils";

function yamlString(s: string): string {
	return JSON.stringify(s);
}

export function buildNoteContent(session: WorkoutSession, store: WorkoutStore): string {
	const exMap = store.exerciseMap();
	const records = sessionRecords(session, store.data.sessions, exMap);
	const duration = sessionDurationMin(session);
	const volume = sessionVolume(session);
	const names = Array.from(
		new Set(session.exercises.map((e) => exMap.get(e.exerciseId)?.name ?? "Unknown exercise"))
	);

	const fm: string[] = ["---"];
	fm.push(`date: ${session.date}`);
	fm.push(`workout: ${yamlString(session.name)}`);
	if (duration !== null) fm.push(`duration_min: ${duration}`);
	fm.push(`total_sets: ${sessionSetCount(session)}`);
	fm.push(`total_volume_kg: ${Math.round(volume)}`);
	fm.push(`prs: ${records.size}`);
	fm.push("exercises:");
	for (const n of names) fm.push(`  - ${yamlString(n)}`);
	fm.push("tags:");
	fm.push("  - workout");
	fm.push("---");

	const body: string[] = [];
	body.push(`# ${session.name} — ${formatDate(session.date)}`);
	body.push("");
	const meta: string[] = [];
	if (session.finishedAt)
		meta.push(`${formatTimeOfDay(session.startedAt)}–${formatTimeOfDay(session.finishedAt)} (${duration} min)`);
	meta.push(`${sessionSetCount(session)} sets`);
	if (volume > 0) meta.push(`${formatNumber(volume, 0)} kg volume`);
	if (records.size) meta.push(`🏆 ${records.size} PR${records.size > 1 ? "s" : ""}`);
	body.push(meta.join(" · "));
	body.push("");
	body.push("> [!info] Generated by the Workout Tracker plugin");
	body.push("> Edit this workout from the plugin's History tab — manual edits to this note are overwritten.");

	session.exercises.forEach((se, ei) => {
		const ex = exMap.get(se.exerciseId);
		if (!ex) return;
		body.push("");
		body.push(`## ${ex.name}`);
		body.push("");
		const done = se.sets.map((s, si) => ({ s, si })).filter((x) => x.s.done);
		body.push(...exerciseTable(ex, done.map((x) => x.s), (i) => records.get(`${ei}:${done[i].si}`)));
		const v = doneSets(se).reduce((acc, s) => acc + (s.weight ?? 0) * (s.reps ?? 0), 0);
		if (ex.type === "weight_reps" && v > 0) {
			body.push("");
			body.push(`**Volume:** ${formatNumber(v, 0)} kg`);
		}
	});

	if (session.notes?.trim()) {
		body.push("");
		body.push("## Notes");
		body.push("");
		body.push(session.notes.trim());
	}

	return `${fm.join("\n")}\n\n${body.join("\n")}\n`;
}

function exerciseTable(ex: Exercise, sets: SetEntry[], recordsFor: (i: number) => string[] | undefined): string[] {
	const pr = (i: number) => {
		const r = recordsFor(i);
		return r ? ` 🏆 ${r.join(", ")} PR` : "";
	};
	const rows: string[] = [];
	switch (ex.type) {
		case "weight_reps":
			rows.push("| Set | Weight (kg) | Reps | e1RM (kg) |", "|---|---|---|---|");
			sets.forEach((s, i) =>
				rows.push(`| ${i + 1} | ${formatNumber(s.weight ?? 0)} | ${s.reps ?? 0} | ${formatNumber(e1rm(s.weight ?? 0, s.reps ?? 0))}${pr(i)} |`)
			);
			break;
		case "bodyweight_reps":
			rows.push("| Set | Reps | Added weight (kg) |", "|---|---|---|");
			sets.forEach((s, i) => rows.push(`| ${i + 1} | ${s.reps ?? 0}${pr(i)} | ${s.weight ? formatNumber(s.weight) : "—"} |`));
			break;
		case "time":
			rows.push("| Set | Time |", "|---|---|");
			sets.forEach((s, i) => rows.push(`| ${i + 1} | ${formatDuration(s.duration ?? 0)}${pr(i)} |`));
			break;
		case "cardio":
			rows.push("| Set | Distance (km) | Time | Pace |", "|---|---|---|---|");
			sets.forEach((s, i) => {
				const pace = s.distance && s.duration ? `${formatDuration(s.duration / s.distance)} /km` : "—";
				rows.push(`| ${i + 1} | ${s.distance ? formatNumber(s.distance, 2) : "—"}${pr(i)} | ${s.duration ? formatDuration(s.duration) : "—"} | ${pace} |`);
			});
			break;
	}
	return rows;
}

async function ensureFolder(app: App, folder: string): Promise<void> {
	if (!folder || folder === "/") return;
	if (app.vault.getAbstractFileByPath(folder)) return;
	const parent = folder.split("/").slice(0, -1).join("/");
	if (parent) await ensureFolder(app, parent);
	await app.vault.createFolder(folder);
}

/** Creates or overwrites the note for a session and returns its path. */
export async function writeSessionNote(app: App, store: WorkoutStore, session: WorkoutSession): Promise<string> {
	const content = buildNoteContent(session, store);
	if (session.notePath) {
		const existing = app.vault.getAbstractFileByPath(session.notePath);
		if (existing instanceof TFile) {
			await app.vault.modify(existing, content);
			return existing.path;
		}
	}
	const folder = normalizePath(store.settings.notesFolder || "/");
	await ensureFolder(app, folder);
	const base = `${session.date} ${sanitizeFileName(session.name)}`;
	const prefix = folder === "/" ? "" : `${folder}/`;
	let path = normalizePath(`${prefix}${base}.md`);
	for (let n = 2; app.vault.getAbstractFileByPath(path); n++) path = normalizePath(`${prefix}${base} (${n}).md`);
	const file = await app.vault.create(path, content);
	return file.path;
}

export async function deleteSessionNote(app: App, session: WorkoutSession): Promise<void> {
	if (!session.notePath) return;
	const f = app.vault.getAbstractFileByPath(session.notePath);
	if (f instanceof TFile) await app.fileManager.trashFile(f);
}
